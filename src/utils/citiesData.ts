/**
 * Format internal city key to capital readable text
 * e.g. "san_francisco" -> "San Francisco"
 */
export const formatCityName = (cityKey: string): string => {
	if (!cityKey) return "";
	const clean = cityKey
		.replace(/_ks$|_mo$|_ia$|_ne$|_tx$|_nm$|_wa$|_ar$/i, "")
		.replace(/_/g, " ");

	return clean
		.split(" ")
		.map((w) => w.charAt(0).toUpperCase() + w.slice(1).toLowerCase())
		.join(" ");
};

/**
 * Get country or US state for a given city dynamically in the current locale
 */
export const getCityCountryOrState = (
	cityKey: string,
	game: "ets2" | "ats",
	locale: string = "es-CL"
): string => {
	const normalizedKey = cityKey.toLowerCase().trim();

	if (game === "ats") {
		if (ATS_CITY_STATE[normalizedKey]) {
			return ATS_CITY_STATE[normalizedKey];
		}
		const baseKey = normalizedKey.replace(/_[a-z]{2}$/, "");
		if (ATS_CITY_STATE[baseKey]) {
			return ATS_CITY_STATE[baseKey];
		}
		return "USA";
	}

	// ETS2: Use ISO Code and Intl.DisplayNames for automatic localization across all 17 languages
	const isoCode =
		ETS2_CITY_COUNTRY_ISO[normalizedKey] ||
		ETS2_CITY_COUNTRY_ISO[normalizedKey.replace(/_[a-z]{2}$/, "")];

	if (isoCode) {
		try {
			// Extract language code from locale e.g. "es-CL" -> "es", "de-DE" -> "de"
			const lang = locale.split("-")[0] || "en";
			const regionNames = new Intl.DisplayNames([lang, "en"], {
				type: "region",
			});
			const countryName = regionNames.of(isoCode);
			if (countryName) return countryName;
		} catch {
			// Fallback if Intl is unavailable
			return isoCode;
		}
	}

	return "";
};
