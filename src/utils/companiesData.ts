/**
 * Format internal company key to official brand name
 * e.g. "wal_mkt" -> "Walbert", "eurogoodies" -> "EuroGoodies"
 */
export const formatCompanyName = (
	companyKey: string,
	game: "ets2" | "ats"
): string => {
	if (!companyKey) return "";
	const normalizedKey = companyKey.toLowerCase().trim();

	if (game === "ats") {
		if (ATS_COMPANIES[normalizedKey]) {
			return ATS_COMPANIES[normalizedKey];
		}
	} else {
		if (ETS2_COMPANIES[normalizedKey]) {
			return ETS2_COMPANIES[normalizedKey];
		}
	}

	// Clean fallback formatting for custom / mod / new DLC companies
	const clean = companyKey.replace(/_/g, " ");
	return clean
		.split(" ")
		.map((w) => w.charAt(0).toUpperCase() + w.slice(1).toLowerCase())
		.join(" ");
};
